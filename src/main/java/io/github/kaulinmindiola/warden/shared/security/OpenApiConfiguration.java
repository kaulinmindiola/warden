package io.github.kaulinmindiola.warden.shared.security;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.info.License;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;
import io.swagger.v3.oas.models.servers.Server;
import java.util.List;
import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * The OpenAPI document of the API (REQ-MAINT-008), generated by springdoc from the controllers.
 * Every operation requires the bearer access token except the public endpoints of {@link
 * SecurityConfiguration}, so the document and the security rules share one list.
 *
 * <p>The document is served at {@code /v3/api-docs} to authenticated callers only, and versioned
 * as {@code docs/api/openapi.json}, which {@code OpenApiDocumentIT} keeps in step with the code.
 */
@Configuration(proxyBeanMethods = false)
public class OpenApiConfiguration {

    /** Name of the security scheme of the access token. */
    public static final String BEARER = "bearer";

    /** Version of the API document, the release it describes. */
    static final String DOCUMENT_VERSION = "1.0.0";

    @Bean
    OpenAPI wardenOpenApi() {
        return new OpenAPI()
                .info(new Info()
                        .title("Warden API")
                        .version(DOCUMENT_VERSION)
                        .description("Identity, sessions, workspaces with roles, notes and notifications. Errors"
                                + " are RFC 9457 problem details; their types are listed in"
                                + " docs/api/problem-types.md.")
                        .license(new License().name("Apache-2.0").url("https://www.apache.org/licenses/LICENSE-2.0")))
                .servers(List.of(new Server()
                        .url("http://localhost:8080")
                        .description("Reference environment (docker compose up -d --wait)")))
                .components(new Components()
                        .addSecuritySchemes(
                                BEARER,
                                new SecurityScheme()
                                        .type(SecurityScheme.Type.HTTP)
                                        .scheme("bearer")
                                        .bearerFormat("JWT")
                                        .description("Access token of a login or refresh response, sent only in"
                                                + " the Authorization header (REQ-INT-002)")));
    }

    /** Marks every operation outside the public endpoints as requiring the access token. */
    @Bean
    OpenApiCustomizer bearerOnProtectedOperations() {
        return openApi -> openApi.getPaths().forEach((path, item) -> {
            if (!SecurityConfiguration.PUBLIC_API_PATHS.contains(path)) {
                item.readOperations()
                        .forEach(operation -> operation.addSecurityItem(new SecurityRequirement().addList(BEARER)));
            }
        });
    }
}
